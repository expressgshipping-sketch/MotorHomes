export const getAccessoryById = (id: number): Accessory | undefined => {
  return accessories.find((a) => a.id === id);
};

export const getAccessoriesByCategory = (category: string): Accessory[] => {
  return accessories.filter((a) => a.category === category);
};

export const getAccessoriesByBrand = (brand: string): Accessory[] => {
  return accessories.filter((a) => a.brand.toLowerCase() === brand.toLowerCase());
};


